const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

const projectRoot = resolve(__dirname, '..');
const changelogPath = resolve(projectRoot, 'CHANGELOG.md');
const packagePath = resolve(projectRoot, 'package.json');
const outputPath = resolve(projectRoot, 'docs/assets/changelog-data.js');

function cleanInlineMarkdown(value) {
  return value
    .replace(/\[([^\]]+)]\([^)]+\)/g, '$1')
    .replace(/[*`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseChangelog(markdown) {
  const releases = [];
  let release = null;
  let section = null;
  let item = null;

  for (const rawLine of markdown.split(/\r?\n/)) {
    const releaseMatch = rawLine.match(/^## \[([^\]]+)] - (\d{4}-\d{2}-\d{2})$/);
    if (releaseMatch) {
      release = { version: releaseMatch[1], date: releaseMatch[2], sections: [] };
      releases.push(release);
      section = null;
      item = null;
      continue;
    }

    if (!release) continue;

    const sectionMatch = rawLine.match(/^### (.+)$/);
    if (sectionMatch) {
      section = { type: sectionMatch[1].trim(), items: [] };
      release.sections.push(section);
      item = null;
      continue;
    }

    const itemMatch = rawLine.match(/^- (.+)$/);
    if (itemMatch && section) {
      item = cleanInlineMarkdown(itemMatch[1]);
      section.items.push(item);
      continue;
    }

    const nestedItemMatch = rawLine.match(/^\s{2,}- (.+)$/);
    if (nestedItemMatch && section && item) {
      const nestedText = cleanInlineMarkdown(nestedItemMatch[1]);
      const lastIndex = section.items.length - 1;
      section.items[lastIndex] = `${section.items[lastIndex]}；${nestedText}`;
      item = section.items[lastIndex];
      continue;
    }

    if (rawLine.trim() && section && item && !rawLine.startsWith('#')) {
      const continuation = cleanInlineMarkdown(rawLine);
      if (continuation) {
        const lastIndex = section.items.length - 1;
        section.items[lastIndex] = `${section.items[lastIndex]} ${continuation}`;
        item = section.items[lastIndex];
      }
    }
  }

  return releases.filter((entry) => entry.sections.some((entrySection) => entrySection.items.length));
}

const changelog = readFileSync(changelogPath, 'utf8');
const packageJson = JSON.parse(readFileSync(packagePath, 'utf8'));
const releases = parseChangelog(changelog);

if (releases.length === 0) {
  throw new Error('CHANGELOG.md 中没有可同步的版本记录');
}

if (releases[0].version !== packageJson.version) {
  throw new Error(`最新 Changelog 版本 ${releases[0].version} 与 package.json 版本 ${packageJson.version} 不一致`);
}

const generated = `// Auto-generated by scripts/sync-pages-changelog.js. Do not edit directly.\nwindow.CLOUDSSH_CHANGELOG = ${JSON.stringify({ releases }, null, 2)};\n`;
writeFileSync(outputPath, generated);

console.log(`Synced ${releases.length} releases to docs/assets/changelog-data.js`);
